// Writes the PocketRails ABI from Foundry's build output into the TypeScript SDK, so the
// SDK, relayer, agents and web app always match the compiled contract.
// Usage: node tools/export-abi.mjs   (after `make build`)
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync("contracts/out/PocketRails.sol/PocketRails.json", "utf8"));
const out = `// Generated by tools/export-abi.mjs from contracts/src/PocketRails.sol. Do not edit by hand.
export const pocketRailsAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync("packages/pocket-rails/src/abi.ts", out);
console.log(`✓ ${artifact.abi.length} ABI entries written to packages/pocket-rails/src/abi.ts`);
